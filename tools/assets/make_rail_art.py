#!/usr/bin/env python3
"""Railroad tiles for the map's close-up track (Map/RoadLayer; 2026-10-12, after the track looked poor
in the trailer): detailed rail (RailroadPass, railroad.frag.glsl
railDetailCoverage): a tile is a 3 x 3 grid, the two rails along its sides and a tie in its middle, and
its corners the two sides the turn joins and the tie. White on clear, tinted in the game.

  assets/rails/<kind>.png   h, v, tl, tr, bl, br; CELL px a sub-cell, 3 x CELL square

--upload sends them through tools/upload.py (STUDIO_ID / STUDIO_MATCH pick the Studio window) and
writes src/shared/Assets/RailArt.luau.

Usage: .venv/bin/python tools/assets/make_rail_art.py [--upload]
"""
import argparse
import os
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "assets", "rails")
MANIFEST = os.path.join(ROOT, "src", "shared", "Assets", "RailArt.luau")
CELL = 8

# which of the 3 x 3 sub-cells are rail (railDetailCoverage: w = 1/3, the band is the side row/column)
KINDS = {
    "h": lambda x, y: y == 0 or y == 2 or (x == 1 and y == 1),
    "v": lambda x, y: x == 0 or x == 2 or (x == 1 and y == 1),
    "tl": lambda x, y: y == 0 or x == 0 or (x == 1 and y == 1),
    "tr": lambda x, y: y == 0 or x == 2 or (x == 1 and y == 1),
    "bl": lambda x, y: y == 2 or x == 0 or (x == 1 and y == 1),
    "br": lambda x, y: y == 2 or x == 2 or (x == 1 and y == 1),
}


def make():
    os.makedirs(OUT, exist_ok=True)
    for k, hit in KINDS.items():
        img = Image.new("RGBA", (3 * CELL, 3 * CELL), (255, 255, 255, 0))
        for y in range(3):
            for x in range(3):
                if hit(x, y):
                    img.paste((255, 255, 255, 255), (x * CELL, y * CELL, (x + 1) * CELL, (y + 1) * CELL))
        img.save(os.path.join(OUT, k + ".png"))


def upload():
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import upload as up
    paths = {k: os.path.join(OUT, k + ".png") for k in KINDS}
    ids = up.upload_images(list(paths.values()))
    L = ["-- GENERATED by tools/assets/make_rail_art.py — do not edit by hand.",
         "-- Railroad tiles for the map's close-up track (Map/RoadLayer): the detailed rail, white.",
         "return {"]
    for k in KINDS:
        L.append(f'\t{k} = "{ids[paths[k]]}",')
    L.append("}")
    with open(MANIFEST, "w") as f:
        f.write("\n".join(L) + "\n")
    print("manifest ->", os.path.relpath(MANIFEST, ROOT))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--upload", action="store_true")
    args = ap.parse_args()
    make()
    print("wrote", os.path.relpath(OUT, ROOT))
    if args.upload:
        upload()


if __name__ == "__main__":
    main()
