#!/usr/bin/env python3
"""The cosmetic crate's 2D art (assets/crate/*.svg; the chest itself is 3D, Assets/CrateModel): icon (a
128 px white mask: UITheme icon "crate"), rays / glow / sparkle and the procedural ring / beam / flare /
streak (white masks for the opening show and the title's crate button: CrateOpening, CrateButton), uploaded as the group with Open Cloud,
written to src/shared/Assets/CrateArt.luau { key = "rbxassetid://.." }.

Usage: .venv/bin/python tools/assets/make_crate_art.py --group 421623341 [--no-upload]
"""
import argparse
import hashlib
import io
import os
import sys
import time

import numpy as np
import resvg_py
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import upload_audio as ua  # noqa: E402

ROOT = ua.ROOT
SRC = os.path.join(ROOT, "assets", "crate")
OUT = os.path.join(ROOT, "build", "crate")
MANIFEST = os.path.join(ROOT, "src", "shared", "Assets", "CrateArt.luau")
FORMAT = "crate-v1"


def render(name, px, mask):
    svg = open(os.path.join(SRC, name), encoding="utf-8").read()
    im = Image.open(io.BytesIO(bytes(resvg_py.svg_to_bytes(svg_string=svg, width=px, height=px)))).convert("RGBA")
    if mask:
        a = np.array(im)
        a[..., 0:3] = 255  # white everywhere; coverage in alpha (tint with ImageColor3)
        im = Image.fromarray(a)
    p = os.path.join(OUT, name.replace(".svg", ".png"))
    im.save(p, optimize=True)
    return p


def procedural(name, w, h, alpha):
    """A white mask from an alpha function of normalised coordinates (x, y in [-1, 1], y down)."""
    ys, xs = np.mgrid[0:h, 0:w].astype(np.float64)
    x = (xs + 0.5) / w * 2 - 1
    y = (ys + 0.5) / h * 2 - 1
    a = np.clip(alpha(x, y), 0, 1)
    im = np.zeros((h, w, 4), np.uint8)
    im[..., 0:3] = 255
    im[..., 3] = np.round(a * 255).astype(np.uint8)
    p = os.path.join(OUT, name + ".png")
    Image.fromarray(im).save(p, optimize=True)
    return p


def ring(x, y):
    # the shockwave / floor ring: a soft band at r = 0.8, a faint fill inside
    r = np.sqrt(x * x + y * y)
    return np.exp(-(((r - 0.8) / 0.075) ** 2)) + 0.12 * np.clip(1 - r / 0.8, 0, 1) * (r < 0.8)


def beam(x, y):
    # the light column out of the open chest (anchor it at the bottom centre): soft sides, fading upward
    v = (y + 1) / 2  # 0 top .. 1 bottom
    return np.exp(-((x / 0.42) ** 2)) * (v ** 1.6) * np.clip((1 - v) / 0.06, 0, 1) ** 0.5


def flare(x, y):
    # the light leaking out of the lid's seam: a thin horizontal flare
    return np.exp(-((y / 0.18) ** 2)) * np.clip(1 - np.abs(x), 0, 1) ** 1.4


def streak(x, y):
    # an air streak past the falling chest
    return np.exp(-((x / 0.3) ** 2)) * np.clip(1 - np.abs(y), 0, 1) ** 1.2


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--group", default="")
    ap.add_argument("--no-upload", action="store_true")
    args = ap.parse_args()
    prefix = ""
    if args.group:
        ua.CREATOR = {"groupId": str(args.group)}
        prefix = f"g{args.group}:"
    os.makedirs(OUT, exist_ok=True)
    files = {
        "icon": render("crate_icon.svg", 128, True),
        "rays": render("rays.svg", 512, True),
        "glow": render("glow.svg", 256, True),
        "sparkle": render("sparkle.svg", 64, True),
        "ring": procedural("ring", 256, 256, ring),
        "beam": procedural("beam", 128, 512, beam),
        "flare": procedural("flare", 512, 64, flare),
        "streak": procedural("streak", 32, 256, streak),
    }
    print("rendered", ", ".join(os.path.relpath(p, ROOT) for p in files.values()))
    if args.no_upload:
        return
    cache = ua.load_cache()
    ids = {}
    for key, p in files.items():
        ck = f"{prefix}{FORMAT}:{hashlib.sha256(open(p, 'rb').read()).hexdigest()}"
        e = cache.get(ck) or {}
        aid = e.get("asset_id")
        if aid is None:
            label = f"Rofront crate {key}"
            op_id = e.get("pending_op") or ua.upload_start(p, label, "Rofront cosmetic crate art", "Image")
            cache[ck] = {"pending_op": op_id, "name": label}
            ua.save_cache(cache)
            aid, resp = ua.upload_wait(op_id)
            mod = (resp.get("moderationResult") or {}).get("moderationState", "?")
            cache[ck] = {"asset_id": aid, "name": label, "moderation": mod, "uploaded": time.strftime("%Y-%m-%d %H:%M:%S")}
            ua.save_cache(cache)
            print(f"{key}: rbxassetid://{aid} moderation={mod}")
        ids[key] = aid
    with open(MANIFEST, "w") as f:
        f.write("-- GENERATED by tools/assets/make_crate_art.py — do not edit by hand.\n")
        f.write("-- The cosmetic crate's 2D art (the chest itself is 3D: Assets/CrateModel): white masks, tint them.\n")
        f.write("return {\n")
        for k in sorted(ids):
            f.write(f'\t{k} = "rbxassetid://{ids[k]}",\n')
        f.write("}\n")
    print("manifest ->", os.path.relpath(MANIFEST, ROOT))


if __name__ == "__main__":
    main()
