#!/usr/bin/env python3
"""Branding art for AIRFRONT on Roblox (re-runnable).

Outputs:
  assets/branding/experience_icon_512.png  Experience icon for publishing (512×512, opaque, full-bleed:
                                           the app icon's rounded navy tile is extended to the square
                                           edges because Roblox applies its own corner mask).
  assets/branding/logo_mark_512.png        In-game title emblem = the app icon exactly (transparent
                                           rounded corners, 512 px) — identical bytes to
                                           assets/ui_icons/app_icon.png, so it shares its asset id.
  src/shared/Assets/Branding.luau          { logo_mark = "rbxassetid://…", app_icon = "rbxassetid://…" }

Source: ~/games/airfront/assets/icons/app_icon.svg (never modified).
Usage:  .venv/bin/python tools/assets/make_branding.py [--no-upload]
"""
import argparse
import os
import re
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_ui_icons as icons  # noqa: E402

ROOT = icons.ROOT
OUT = os.path.join(ROOT, "assets", "branding")
MANIFEST = os.path.join(ROOT, "src", "shared", "Assets", "Branding.luau")
APP_SVG = os.path.join(icons.SRC, "icons", "app_icon.svg")


def render_string(svg, px):
    import io

    import resvg_py
    png = bytes(resvg_py.svg_to_bytes(svg_string=svg, width=px, height=px))
    return Image.open(io.BytesIO(png)).convert("RGBA")


def experience_icon(px=512):
    svg = open(APP_SVG, encoding="utf-8").read()
    full, n = re.subn(r'<rect x="8" y="8" width="240" height="240" rx="56"',
                      '<rect x="0" y="0" width="256" height="256"', svg, count=1)
    assert n == 1, "app_icon.svg background rect changed; update make_branding.py"
    img = render_string(full, px)
    a = np.asarray(img)
    assert a[..., 3].min() == 255, "experience icon must be opaque"
    return img.convert("RGB")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-upload", action="store_true")
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    exp = os.path.join(OUT, "experience_icon_512.png")
    experience_icon(512).save(exp, optimize=True)
    files = icons.render_all()              # (re)renders assets/ui_icons/app_icon.png deterministically
    logo = os.path.join(OUT, "logo_mark_512.png")
    Image.open(files["app_icon"]).save(logo, optimize=True)
    print("wrote", os.path.relpath(exp, ROOT), "and", os.path.relpath(logo, ROOT))
    if args.no_upload:
        return
    os.environ.setdefault("STUDIO_MATCH", "assets.rbxl")
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import upload  # noqa: E402
    res = upload.upload_images([files["app_icon"]])
    app_id = res[os.path.abspath(files["app_icon"])]
    with open(MANIFEST, "w") as f:
        f.write("\n".join([
            "-- GENERATED by tools/assets/make_branding.py — do not edit by hand.",
            "-- In-game branding images (full colour, do not tint). logo_mark = the title-screen emblem",
            "-- (TitleScreen `_emblem`, RotateCard icon) = AIRFRONT's app icon, 512×512 with transparent",
            "-- rounded corners. The publishing icon (assets/branding/experience_icon_512.png) is not",
            "-- used in game and is set in the experience settings instead.",
            "return {",
            f'\tapp_icon = "{app_id}",',
            f'\tlogo_mark = "{app_id}",',
            "}",
        ]) + "\n")
    print("manifest ->", os.path.relpath(MANIFEST, ROOT))


if __name__ == "__main__":
    main()
