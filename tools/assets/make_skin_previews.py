#!/usr/bin/env python3
"""The territory skins' previews (Locker cards, the crate reveal) as one uploaded atlas: each skin's pattern
in the Locker's PREVIEW_COLOR over sand, exactly as Locker's EditableImage preview drew it (PREVIEW_TILES
square, a darker border, the fill at alpha 150, secondary tiles at Cosmetics.SECONDARY_ALPHA), scaled up
nearest-neighbour. On 2026-09-29 an Epic skin's reveal card came out empty on a phone — the runtime
EditableImage preview can't be created when the device's EditableImage budget is spent (the map's layers),
so the previews ship as an image. Uploaded as the group with Open Cloud; writes
src/shared/Assets/SkinPreviews.luau:

  { image = "rbxassetid://..", cells = { stripes = { x, y, w, h }, ... } }

Usage: .venv/bin/python tools/assets/make_skin_previews.py --group 421623341 [--no-upload]
"""
import argparse
import hashlib
import os
import sys
import time

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import preview_skins as ps  # noqa: E402
import upload_audio as ua  # noqa: E402

ROOT = ua.ROOT
OUT = os.path.join(ROOT, "build", "skins")
MANIFEST = os.path.join(ROOT, "src", "shared", "Assets", "SkinPreviews.luau")
FORMAT = "skin-previews-v1"
# (Locker.PREVIEW_COLOR / PREVIEW_TILES, MapSurface's terrain sand, the fill alphas)
PREVIEW_COLOR = (64, 132, 230)
TILES = 24
SCALE = 4
GAP = 4
COLS = 7
TERRAIN = (221, 205, 160)
ALPHA1, ALPHA2 = 150, 190


def render(s):
    """One skin's card: TILES x TILES tiles at SCALE px (a skin with several colours: twice the tiles at
    half the size, so its larger pattern shows whole, e.g. Tie Dye's 32-tile swirls). Always TILES * SCALE px."""
    n = TILES * 2 if s.get("colors") else TILES
    r, g, b = (c / 255 for c in PREVIEW_COLOR)
    sr, sg, sb = ps.second(s, r, g, b)
    w = max(len(row) for row in s["rows"])
    h = len(s["rows"])
    im = Image.new("RGBA", (n, n))
    px = im.load()
    for y in range(n):
        for x in range(n):
            if x in (0, n - 1) or y in (0, n - 1):
                cr, cg, cb, a = r * 0.875, g * 0.875, b * 0.875, 1.0
            else:
                row = s["rows"][(y >> s["scale"]) % h]
                mx = (x >> s["scale"]) % w
                (cr, cg, cb), a = ps.tile_color(s, row, mx, (r, g, b), (sr, sg, sb))
                a /= 255
            t = [v / 255 for v in TERRAIN]
            px[x, y] = tuple(int((t[i] * (1 - a) + c * a) * 255 + 0.5) for i, c in enumerate((cr, cg, cb))) + (255,)
    return im.resize((TILES * SCALE, TILES * SCALE), Image.NEAREST)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--group", default="")
    ap.add_argument("--no-upload", action="store_true")
    args = ap.parse_args()
    prefix = ""
    if args.group:
        ua.CREATOR = {"groupId": str(args.group)}
        prefix = f"g{args.group}:"
    skins = ps.skins()
    cell = TILES * SCALE
    rows = (len(skins) + COLS - 1) // COLS
    sheet = Image.new("RGBA", (COLS * (cell + GAP), rows * (cell + GAP)), (0, 0, 0, 0))
    cells = {}
    for i, s in enumerate(skins):
        x, y = (i % COLS) * (cell + GAP), (i // COLS) * (cell + GAP)
        sheet.alpha_composite(render(s), (x, y))
        cells[s["id"]] = (x, y, cell, cell)
    os.makedirs(OUT, exist_ok=True)
    p = os.path.join(OUT, "skin_previews.png")
    sheet.save(p, optimize=True)
    print(f"{len(skins)} skins -> {os.path.relpath(p, ROOT)}")
    if args.no_upload:
        return
    cache = ua.load_cache()
    ck = f"{prefix}{FORMAT}:{hashlib.sha256(open(p, 'rb').read()).hexdigest()}"
    e = cache.get(ck) or {}
    aid = e.get("asset_id")
    if aid is None:
        label = "Rofront skin previews"
        op_id = e.get("pending_op") or ua.upload_start(p, label, "Rofront territory skin previews", "Image")
        cache[ck] = {"pending_op": op_id, "name": label}
        ua.save_cache(cache)
        aid, resp = ua.upload_wait(op_id)
        mod = (resp.get("moderationResult") or {}).get("moderationState", "?")
        cache[ck] = {"asset_id": aid, "name": label, "moderation": mod, "uploaded": time.strftime("%Y-%m-%d %H:%M:%S")}
        ua.save_cache(cache)
        print(f"rbxassetid://{aid} moderation={mod}")
    L = [
        "-- GENERATED by tools/assets/make_skin_previews.py — do not edit by hand.",
        "-- The territory skins' previews in one atlas (Locker cards, the crate reveal): each skin's pixel rect",
        "-- (ImageRectOffset = x, y; ImageRectSize = w, h). Draw with ResampleMode Pixelated.",
        "return {",
        f'\timage = "rbxassetid://{aid}",',
        "\tcells = {",
    ]
    for sid, (x, y, w, h) in cells.items():
        L.append(f"\t\t{sid} = {{ {x}, {y}, {w}, {h} }},")
    L += ["\t},", "}"]
    with open(MANIFEST, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("manifest ->", os.path.relpath(MANIFEST, ROOT))


if __name__ == "__main__":
    main()
