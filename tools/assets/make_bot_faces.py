#!/usr/bin/env python3
"""Head shots for bot players (2026-10-04): now that people show their Roblox head shot beside their
names, bot players show random real Roblox avatars.

Picks random Roblox user ids and keeps the ones that would draw a head shot in the game:
  - the account exists and is not banned (users.roblox.com/v1/users, excludeBannedUsers);
  - its head shot is rendered (thumbnails.roblox.com avatar-headshot: state Completed);
  - at most SAME accounts share one image, and at most LOOK_SHARE of the pool one outline (most
    accounts picked at random never dressed: they wear one of a few default looks in different skin
    and shirt colours, and the first pool was two thirds the same "bacon hair". An outline is the
    head shot's silhouette, 12 x 12; outlines within NEAR cells of each other are one look);
  - it reads as a head: not a frame filled edge to edge, not a speck, not one flat colour.
Only the ids are kept (src/server/BotFaces.luau, server only: a client that could read the pool could
tell bot players by it). MatchServer deals them to a match's bot players. build/bot_faces_sheet.png
shows the pool. Accounts get banned over time: run it again now and then.

Usage: .venv/bin/python tools/assets/make_bot_faces.py [--count 400] [--no-sheet]
"""
import argparse
import io
import json
import os
import random
import time
import urllib.request

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "server", "BotFaces.luau")
SHEET = os.path.join(ROOT, "build", "bot_faces_sheet.png")
LO, HI = 100_000_000, 8_000_000_000
SAME = 2
LOOK_SHARE = 0.04
NEAR = 8
BATCH = 100


def outline(png):
    """The head shot's silhouette as 144 bits (its alpha, 12 x 12); None when it doesn't read as a head."""
    from PIL import Image, ImageStat
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    alpha = im.getchannel("A")
    cover = ImageStat.Stat(alpha).mean[0] / 255.0
    if cover > 0.95 or cover < 0.12:
        return None
    if ImageStat.Stat(im.convert("L"), alpha.point(lambda v: 255 if v > 127 else 0)).stddev[0] < 14:
        return None
    return [1 if v > 127 else 0 for v in alpha.resize((12, 12), Image.BOX).getdata()]


def get(url, body=None):
    headers = {"Accept": "application/json"}
    data = None
    if body is not None:
        data = json.dumps(body).encode()
        headers["Content-Type"] = "application/json"
    for attempt in range(5):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, data=data, headers=headers), timeout=30) as r:
                return json.load(r)
        except Exception as e:  # (rate limits: wait and go on)
            time.sleep(2 + attempt * 4)
            last = e
    raise last


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=400)
    ap.add_argument("--no-sheet", action="store_true")
    args = ap.parse_args()
    rnd = random.SystemRandom()
    keep, images, per_image, asked = [], {}, {}, 0
    looks = []  # [outline, how many kept]
    cap = max(4, int(args.count * LOOK_SHARE))
    while len(keep) < args.count:
        ids = [rnd.randint(LO, HI) for _ in range(BATCH)]
        asked += len(ids)
        users = get("https://users.roblox.com/v1/users", {"userIds": ids, "excludeBannedUsers": True})["data"]
        ok = [u["id"] for u in users]
        if not ok:
            continue
        th = get("https://thumbnails.roblox.com/v1/users/avatar-headshot?userIds=" + ",".join(map(str, ok))
                 + "&size=48x48&format=Png&isCircular=false")["data"]
        for t in th:
            url = t.get("imageUrl") or ""
            if t.get("state") != "Completed" or not url:
                continue
            if per_image.get(url, 0) >= SAME:
                continue
            try:
                with urllib.request.urlopen(url, timeout=30) as r:
                    png = r.read()
                o = outline(png)
            except Exception:
                continue
            if o is None:
                continue
            look = None
            for lk in looks:
                if sum(1 for x, y in zip(lk[0], o) if x != y) <= NEAR:
                    look = lk
                    break
            if look is None:
                look = [o, 0]
                looks.append(look)
            if look[1] >= cap:
                continue
            look[1] += 1
            per_image[url] = per_image.get(url, 0) + 1
            keep.append(t["targetId"])
            images[t["targetId"]] = png
            if len(keep) >= args.count:
                break
        print(f"asked {asked}, kept {len(keep)}, {len(looks)} looks", flush=True)
        time.sleep(0.4)
    keep.sort()
    L = ["--!strict",
         "-- GENERATED by tools/assets/make_bot_faces.py — do not edit by hand.",
         "-- Roblox user ids whose head shot a bot player may wear beside its name (2026-10-04: real avatars,",
         "-- not made-up ones): accounts picked at random that exist, are not banned and have a head shot.",
         "-- Server only: MatchServer deals them out (deps.bot_faces), clients only ever see the ones in use.",
         "return {"]
    for i in range(0, len(keep), 8):
        L.append("\t" + ", ".join(str(x) for x in keep[i:i + 8]) + ",")
    L.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"{len(keep)} ids -> {os.path.relpath(OUT, ROOT)} ({len(looks)} looks, at most {cap} of one)")
    if args.no_sheet:
        return
    from PIL import Image
    cols = 25
    rows = (len(keep) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * 50, rows * 50), (24, 30, 52))
    for i, uid in enumerate(keep):
        try:
            im = Image.open(io.BytesIO(images[uid])).convert("RGBA")
            sheet.paste(im, ((i % cols) * 50 + 1, (i // cols) * 50 + 1), im)
        except Exception:
            pass
    os.makedirs(os.path.dirname(SHEET), exist_ok=True)
    sheet.save(SHEET)
    print("sheet ->", os.path.relpath(SHEET, ROOT))


if __name__ == "__main__":
    main()
