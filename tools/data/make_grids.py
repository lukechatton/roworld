#!/usr/bin/env python3
"""Encode the sim's world grids (terrain.png, water_body.png, 1024x512 L8) and data JSON into
Luau modules under src/shared/Data. Re-runnable. Grid encoding: byte-level RLE (value, run-1 as
LEB128 varint) of the whole row-major array, then base64. Decoded by Data/Grids.luau."""
import base64, json, os, sys
from PIL import Image
SRC = os.path.expanduser("~/games/airfront")
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "shared", "Data")
os.makedirs(OUT, exist_ok=True)

def rle(data: bytes) -> bytes:
    out = bytearray(); i = 0; n = len(data)
    while i < n:
        v = data[i]; j = i
        while j < n and data[j] == v: j += 1
        run = j - i - 1
        out.append(v)
        while True:
            b = run & 0x7F; run >>= 7
            out.append(b | (0x80 if run else 0))
            if not run: break
        i = j
    return bytes(out)

def grid(name):
    im = Image.open(os.path.join(SRC, "assets/world", name + ".png"))
    assert im.size == (1024, 512), im.size
    if im.mode != "L": im = im.convert("L")
    raw = im.tobytes()
    enc = base64.b64encode(rle(raw)).decode()
    return enc, raw

parts = []
for name in ("terrain", "water_body"):
    enc, raw = grid(name)
    parts.append((name, enc, len(raw)))
    print(name, "raw", len(raw), "b64", len(enc), "unique", sorted(set(raw))[:12], "...")

with open(os.path.join(OUT, "GridData.luau"), "w") as f:
    f.write("-- GENERATED by tools/data/make_grids.py from ~/games/airfront/assets/world/*.png. Do not edit.\n")
    f.write("-- RLE(value, varint run-1) + base64 of 1024x512 L8 grids, row-major (i = y * 1024 + x).\n")
    f.write("return {\n")
    for name, enc, n in parts:
        f.write(f'\t{name} = {{ size = {n}, data = "')
        f.write(enc)
        f.write('" },\n')
    f.write("}\n")

def lua_value(v, ind=""):
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            key = k if k.isidentifier() else "[%s]" % json.dumps(k)
            items.append(f"{key} = {lua_value(x, ind)}")
        return "{ " + ", ".join(items) + " }"
    if isinstance(v, list):
        return "{ " + ", ".join(lua_value(x, ind) for x in v) + " }"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(v)
    if v is None: return "nil"
    return json.dumps(v, ensure_ascii=False)

nations = json.load(open(os.path.join(SRC, "data/nations.json")))
tribes = json.load(open(os.path.join(SRC, "data/tribes.json")))
with open(os.path.join(OUT, "Nations.luau"), "w") as f:
    f.write("-- GENERATED by tools/data/make_grids.py from data/nations.json. Do not edit.\n")
    f.write("-- Array (1-based) in nations.json order; nation owner id = index (1..88).\n")
    f.write("return {\n")
    for n in nations:
        f.write("\t" + lua_value(n) + ",\n")
    f.write("}\n")
with open(os.path.join(OUT, "Tribes.luau"), "w") as f:
    f.write("-- GENERATED by tools/data/make_grids.py from data/tribes.json. Do not edit.\n")
    f.write("return {\n\tnames = {\n")
    for n in tribes["names"]:
        f.write("\t\t" + json.dumps(n, ensure_ascii=False) + ",\n")
    f.write("\t},\n}\n")
print("nations", len(nations), "tribes", len(tribes["names"]), "keys", list(tribes.keys()))
