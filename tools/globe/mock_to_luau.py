#!/usr/bin/env python3
"""Convert the original's mock world export (tools/globe/export_mock.gd, run headless with the
Airship Editor — see build/notes/globe.md) into src/client/Dev/GlobeMockData.luau for the globe
harness, so the port renders the exact territories of tests/view_mock.tscn's reference shots.

Grid encoding: runs of (value u16, count varuint) over the 524288 tiles, base64."""
import base64
import json
import os
import struct
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else "/private/tmp/claude-501/afexport"
OUT = os.path.join(ROOT, "src", "client", "Dev", "GlobeMockData.luau")


def rle(values):
    out = bytearray()
    n = len(values)
    i = 0
    while i < n:
        v = int(values[i])
        j = i + 1
        while j < n and values[j] == v:
            j += 1
        run = j - i - 1
        out += struct.pack("<H", v)
        while True:
            b = run & 0x7F
            run >>= 7
            if run:
                out.append(b | 0x80)
            else:
                out.append(b)
                break
        i = j
    return base64.b64encode(bytes(out)).decode()


def main():
    meta = json.load(open(os.path.join(SRC, "mock_meta.json")))
    owner = np.frombuffer(open(os.path.join(SRC, "mock_owner.bin"), "rb").read(), dtype="<i4")
    flags = np.frombuffer(open(os.path.join(SRC, "mock_flags.bin"), "rb").read(), dtype=np.uint8)
    lines = ["-- GENERATED by tools/globe/mock_to_luau.py from the original's tests/view_mock_world.gd (seed",
             "-- 1234) — the exact territories of the reference captures. Dev harness data only.",
             "return {",
             f"\tlocal_id = {meta['local_id']},",
             f"\ttick = {meta['tick']},",
             "\towners = {"]
    for o in sorted(meta["owners"], key=lambda r: r[0]):
        name = o[1].replace('"', '\\"')
        lines.append(f'\t\t{{ id = {o[0]}, name = "{name}", color = "#{o[2]}", kind = {o[3]}, traitor_until = {o[5]} }},')
    lines.append("\t},")
    lines.append("\tallies = {" + ", ".join(f"{{{a}, {b}}}" for a, b in meta["allies"]) + "},")
    lines.append(f'\towner_rle = "{rle(owner.astype(np.uint16))}",')
    lines.append(f'\tflags_rle = "{rle(flags.astype(np.uint16))}",')
    lines.append("}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote", OUT, os.path.getsize(OUT), "bytes; local", meta["local_id"])


if __name__ == "__main__":
    main()
