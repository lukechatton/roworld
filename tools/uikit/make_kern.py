#!/usr/bin/env python3
"""ui-kit (polish-fixer): Rubik pair kerning (GPOS 'kern', per weight, em/1000) for letter-spaced text.

Godot shaped the original's letter-spaced labels with HarfBuzz, i.e. WITH the font's pair kerning
("MULTIPLAYER": L|T pulls in by 0.10 em); the kit renders letter-spaced text glyph by glyph from the
advance table in UITheme.luau and needs the kerning pairs to match. Writes src/client/UI/UIKern.luau:
    return { [weight] = "<pair><signed 4-char value>..." }   -- 6-char records, e.g. "LT-102"
Only printable ASCII pairs with |kern| >= MIN_ABS are kept.

Usage: .venv/bin/python tools/uikit/make_kern.py [path/to/Rubik-VariableFont_wght.ttf]
"""
import os
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/godot/airship-app/__builtin/theme/Rubik-VariableFont_wght.ttf")
OUT = os.path.join(ROOT, "src", "client", "UI", "UIKern.luau")
MIN_ABS = 8
WEIGHTS = (400, 500, 600, 700, 800, 900)
CHARS = [chr(c) for c in range(33, 127)]


def pair_kerning(font):
    cmap = font.getBestCmap()
    gpos = font["GPOS"].table
    lookups = set()
    for fr in gpos.FeatureList.FeatureRecord:
        if fr.FeatureTag == "kern":
            lookups.update(fr.Feature.LookupListIndex)
    subtables = []
    for li in sorted(lookups):
        lk = gpos.LookupList.Lookup[li]
        for st in lk.SubTable:
            if lk.LookupType == 9:
                st = st.ExtSubTable
            if getattr(st, "LookupType", 2) == 2 and hasattr(st, "Coverage"):
                subtables.append(st)
    out = {}
    for a in CHARS:
        ga = cmap.get(ord(a))
        if ga is None:
            continue
        for b in CHARS:
            gb = cmap.get(ord(b))
            if gb is None:
                continue
            total = 0
            for st in subtables:
                cov = st.Coverage.glyphs
                if ga not in cov:
                    continue
                if st.Format == 1:
                    for pvr in st.PairSet[cov.index(ga)].PairValueRecord:
                        if pvr.SecondGlyph == gb:
                            total += getattr(pvr.Value1, "XAdvance", 0) or 0
                elif st.Format == 2:
                    c1 = st.ClassDef1.classDefs.get(ga, 0)
                    c2 = st.ClassDef2.classDefs.get(gb, 0)
                    total += getattr(st.Class1Record[c1].Class2Record[c2].Value1, "XAdvance", 0) or 0
            if abs(total) >= MIN_ABS:
                out[a + b] = total
    return out


lines = [
    "-- GENERATED by tools/uikit/make_kern.py from Rubik's GPOS 'kern' pairs. Do not edit.",
    "-- Pair kerning in em/1000 per weight for letter-spaced (per-glyph) text: 6-char records",
    '-- "<first><second><signed value>", e.g. "LT-102" (printable ASCII, |kern| >= %d).' % MIN_ABS,
    "return {",
]
for w in WEIGHTS:
    inst = instantiateVariableFont(TTFont(FONT), {"wght": w}, inplace=False)
    pairs = pair_kerning(inst)
    recs = []
    for k in sorted(pairs):
        v = pairs[k]
        if not -999 <= v <= 999:
            continue
        recs.append(k + ("%+04d" % v))
    blob = "".join(recs)
    # Luau long string: records never contain "]]" as a closing bracket pair followed by "="
    assert "]]" not in blob
    lines.append("\t[%d] = [[%s]]," % (w, blob))
    print(w, len(recs), "pairs")
lines.append("}")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT)
