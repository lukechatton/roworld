#!/usr/bin/env python3
"""ui-kit: generate + upload the kit's textures and write src/shared/Assets/UIKit.luau.

- shadows: soft-shadow 9-slices (Godot StyleBoxFlat shadow = rounded rect grown by shadow_size with a
  linear alpha falloff). One texture per corner-radius / feather ratio; the kit picks the nearest
  ratio and scales the slices so the feather is exact.
- spinner_arc / spinner_ring: BusyChip spinner (Godot draw_arc(r = size/2 - 2, width 2.5) of an 18 px
  control): a 1.9 rad arc starting at angle 0 (pointing right, clockwise) and the full ring.

Usage: .venv/bin/python tools/uikit/make_textures.py   (PNG output in build/uikit/)
"""
import math
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import upload  # noqa: E402

OUT = os.path.join(ROOT, "build", "uikit")
MANIFEST = os.path.join(ROOT, "src", "shared", "Assets", "UIKit.luau")
FEATHER = 40
RATIOS = [0.2, 0.35, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0, 1.15, 1.3, 1.5, 1.75, 2.0, 2.5, 3.0]


def save(a, name):
    img = np.zeros(a.shape + (4,), np.uint8)
    img[..., :3] = 255
    img[..., 3] = np.round(np.clip(a, 0, 1) * 255).astype(np.uint8)
    path = os.path.join(OUT, name)
    Image.fromarray(img, "RGBA").save(path)
    return path


# Inside the shadow rect the alpha fades out over RAMP * feather: the panel (drawn on top) is
# translucent, and Godot's frosted glass sampled the backdrop *before* its own shadow, so the shadow
# must not darken what shows through the glass; the ramp still covers the band the shadow's
# offset (6 px down) exposes under the panel.
RAMP = 0.7


def shadow(ratio):
    r = int(round(ratio * FEATHER))
    ramp = RAMP * FEATHER
    inner = max(r, int(np.ceil(ramp))) + 1  # corner slices must contain the radius and the ramp
    c = FEATHER + inner
    size = 2 * c + 4
    ys, xs = np.mgrid[0:size, 0:size].astype(np.float64) + 0.5
    half = size / 2.0 - FEATHER
    qx = np.abs(xs - size / 2.0) - (half - r)
    qy = np.abs(ys - size / 2.0) - (half - r)
    d = np.sqrt(np.maximum(qx, 0) ** 2 + np.maximum(qy, 0) ** 2) + np.minimum(np.maximum(qx, qy), 0) - r
    a = np.where(d > 0, np.clip(1.0 - d / FEATHER, 0.0, 1.0), np.clip(1.0 + d / ramp, 0.0, 1.0))
    return save(a, f"shadow_r{int(ratio * 100):03d}.png"), r, size, c


def spinner(arc):
    # 18 px control -> texture 144 px (8x). r = 9 - 2 = 7, width 2.5 (px of the 18 px control).
    k = 8
    n = 18 * k
    ys, xs = np.mgrid[0:n, 0:n].astype(np.float64) + 0.5
    cx = cy = n / 2.0
    dx, dy = xs - cx, ys - cy
    rr = np.sqrt(dx * dx + dy * dy)
    r0, hw = 7.0 * k, 1.25 * k
    cov = np.clip(hw + 0.5 - np.abs(rr - r0), 0.0, 1.0)  # 1 texel AA
    if arc:
        ang = np.mod(np.arctan2(dy, dx), 2 * math.pi)  # 0 = right, clockwise (y down)
        span = 1.9
        cov = cov * np.clip((span - ang) * r0 + 0.5, 0, 1) * np.clip(ang * r0 + 0.5, 0, 1)
    return save(cov, "spinner_arc.png" if arc else "spinner_ring.png")


def main():
    os.makedirs(OUT, exist_ok=True)
    sh = [(q,) + shadow(q) for q in RATIOS]
    arc = spinner(True)
    ring = spinner(False)
    ids = upload.upload_images([m[1] for m in sh] + [arc, ring])
    lines = [
        "-- GENERATED by tools/uikit/make_textures.py - do not edit by hand.",
        "-- ui-kit textures. shadows[i] = {id, feather, radius, size, slice}: soft-shadow 9-slices (white,",
        "-- alpha = linear StyleBoxFlat shadow falloff outside, fading out inside; corner slice = `slice` px).",
        "return {",
        "\tshadows = {",
    ]
    for q, path, r, size, c in sh:
        lines.append(f'\t\t{{ id = "{ids[path]}", feather = {FEATHER}, radius = {r}, size = {size}, slice = {c} }}, -- ratio {q}')
    lines += [
        "\t},",
        "\t-- BusyChip spinner: 1.9 rad arc from angle 0 (right, clockwise) and the full ring; 18 px control.",
        f'\tspinner_arc = "{ids[arc]}",',
        f'\tspinner_ring = "{ids[ring]}",',
        "}",
        "",
    ]
    open(MANIFEST, "w").write("\n".join(lines))
    print("wrote", MANIFEST)


if __name__ == "__main__":
    main()
